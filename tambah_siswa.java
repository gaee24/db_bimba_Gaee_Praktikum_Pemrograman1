    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
     try {
            Connection conn = koneksi.getConnection();
            // Query SQL insert data ke tabel siswa
            String sql = "INSERT INTO siswa (nama_siswa, jenis_kelamin, tanggal_lahir, alamat_siswa) VALUES (?, ?, ?, ?)";
            PreparedStatement pst = conn.prepareStatement(sql);
            
            // Mengambil input dari komponen-komponen UI
            pst.setString(1, jTextField1.getText());
            pst.setString(2, jComboBox1.getSelectedItem().toString());
            
            // Memformat tanggal dari JDateChooser ke format database (YYYY-MM-DD)
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            String tanggal = sdf.format(jDateChooser1.getDate());
            pst.setString(3, tanggal);
            
            pst.setString(4, jTextArea1.getText());
            
            // Eksekusi query
            pst.executeUpdate();
            
            JOptionPane.showMessageDialog(null, "Data Berhasil Disimpan!");
            tampilData();
            
            // Membersihkan form input setelah berhasil menyimpan data
            jTextField1.setText("");
            jComboBox1.setSelectedIndex(-1);
            jDateChooser1.setDate(null);
            jTextArea1.setText("");
            jTextField1.requestFocus();
            
            // Memperbarui tampilan data pada tabel
            tampilData();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Penyimpanan Gagal: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

