    private void jTable2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable2MouseClicked
        int baris = jTable2.getSelectedRow();
        
    jTextField1.setText(jTable2.getValueAt(baris, 1).toString());
    
    jComboBox1.setSelectedItem(
        jTable2.getValueAt(baris, 2).toString());
    
    try{
        String tgl =jTable2.getValueAt(baris, 3).toString();
        SimpleDateFormat sdf = 
                new SimpleDateFormat("yyyy-MM-dd");
        Date tanggal =sdf.parse(tgl);
        jDateChooser1.setDate(tanggal);
    }catch (Exception e){
        JOptionPane.showMessageDialog(null, "Tanggal Gagal Di Tampilkan");
    }
    jTextArea1.setText(
        jTable2.getValueAt(baris, 4).toString());
    
    idSiswa = jTable2.getValueAt(baris, 0).toString();
    }//GEN-LAST:event_jTable2MouseClicked

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
            try{
        if(idSiswa == null || idSiswa.equals("")){
                JOptionPane.showMessageDialog(null,"Pilih date yang akan dihapus terlebih dahullu");
                return;
            }
        
        int konfirmasi = JOptionPane.showConfirmDialog(null, 
                "Yakin ingin menghapus data ini ?",
                "Konfirmasi Hapus",
                JOptionPane.YES_NO_OPTION);
        if (konfirmasi == JOptionPane.YES_OPTION){
            Connection conn = koneksi.getConnection();
            String sql = "DELETE FORM siswa WHERE id_siswa=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, idSiswa);
            pst.executeUpdate();
            JOptionPane.showMessageDialog(null, "Data berhasil dihapus");
            
            //refresh tabel
            tampilData();
            
            //kosongkan form
            jTextField1.setText("");
            jComboBox1.setSelectedIndex(-1);
            jDateChooser1.setDate(null);
            
            idSiswa =""; 
            
            }
        } catch (Exception e){
            JOptionPane.showMessageDialog(null,"Data Gagal dihapus : " + e.getMessage());
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try{
           if (idSiswa == null || idSiswa.equals("")){
               JOptionPane.showMessageDialog(null, "Pilih data yang akan diedit terlebih dahulu");
               return;
               
           }
           Connection conn = koneksi.getConnection();
           String sql = "UPDATE siswa SET"
                   + "nama_siswa=?,"
                   + "jenis_kelamin=?,"
                   + "alamat_siswa=?"
                   + "WHERE id_siswa=?";
           
           PreparedStatement pst = conn.prepareStatement(sql);
           pst.setString(1, jTextField1.getText());
           pst.setString(2, jComboBox1.getSelectedItem().toString());
           
           java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
           String tanggal = sdf.format(jDateChooser1.getDate());
           pst.setString(3,tanggal);
           pst.setString(4,jTextArea1.getText());
           pst.setString(5,idSiswa);
           pst.executeUpdate();
           
           JOptionPane.showMessageDialog(null,"Data berhasil diubah");
           tampilData();
           jTextField1.setText("");
           jComboBox1.setSelectedIndex(-1);
           jDateChooser1.setDate(null);
           jTextArea1.setText("");
           
           idSiswa ="";
           
        }catch(Exception e){
            JOptionPane.showMessageDialog(null,"Data gagal diubah : "+ e.getMessage());
            
        }
    }//GEN-LAST:event_jButton2ActionPerformed

