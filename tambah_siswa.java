    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        jTable2.setModel(model);
        model.addColumn("ID Siswa");
        model.addColumn("Nama Siswa");
        model.addColumn("Jenis Kelamin");
        model.addColumn("Tanggal Lahir");
        model.addColumn("Alamat");
        
        try {
            Connection conn = koneksi.getConnection();
            String sql = "SELECT * FROM siswa"; // Query mengambil data dari tabel siswa
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_siswa"), // Sesuaikan dengan nama kolom di database Anda
                    rs.getString("nama_siswa"),
                    rs.getString("jenis_kelamin"),
                    rs.getString("tanggal_lahir"),
                    rs.getString("alamat_siswa")
                });
            }
            // jTable1 adalah nama variabel komponen JTable Anda di design view
            jTable2.setModel(model); 
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal memuat data: " + e.getMessage());
        }
    }
    
